export interface GroupRef {
  /** 族群名，例：被動元件 */
  group: string;
  /** 大類名，例：電子零組件 */
  category: string;
}

/** 代號 → 族群（模組載入時建一次，O(1) 查詢） */
export const CODE_TO_GROUP: ReadonlyMap<string, GroupRef> = (() => {
  const m = new Map<string, GroupRef>();
  for (const [category, groups] of Object.entries(STOCK_GROUPS)) {
    for (const [group, codes] of Object.entries(groups)) {
      for (const code of codes) m.set(code, { group, category });
    }
  }
  return m;
})();

/** 顯示用文字：有收錄回族群名，沒有就退回傳進來的官方產業別（可能是空字串） */
export function groupLabel(code: string, fallback?: string | null): string {
  return CODE_TO_GROUP.get(code)?.group ?? (fallback || '');
}
